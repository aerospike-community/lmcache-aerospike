#!/usr/bin/env bash
# Start Redis in Docker for L2 bench (RESP adapter). Writes .redis-bench.env.
#
# Usage:
#   ./scripts/start_redis_bench.sh
#   set -a && source .redis-bench.env && set +a

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

IMAGE="${REDIS_BENCH_IMAGE:-redis:7-alpine}"
CONTAINER_NAME="${REDIS_BENCH_CONTAINER_NAME:-lmcache-redis-bench}"
ENV_FILE="${REDIS_BENCH_ENV_FILE:-.redis-bench.env}"
HOST_PORT="${REDIS_BENCH_PORT:-6399}"

if ! command -v docker >/dev/null 2>&1; then
  echo "docker is required to start Redis for bench" >&2
  exit 1
fi

echo "Starting Redis (${IMAGE}) as ${CONTAINER_NAME} on 127.0.0.1:${HOST_PORT} ..."
docker rm -f "$CONTAINER_NAME" 2>/dev/null || true

docker run -d \
  --name "$CONTAINER_NAME" \
  -p "${HOST_PORT}:6379" \
  "$IMAGE" \
  redis-server --save "" --appendonly no --protected-mode no

echo "Waiting for Redis PONG (up to 30s) ..."
deadline=$((SECONDS + 30))
until docker exec "$CONTAINER_NAME" redis-cli ping 2>/dev/null | grep -q PONG; do
  if (( SECONDS >= deadline )); then
    echo "Redis did not become ready in time." >&2
    docker logs "$CONTAINER_NAME" 2>&1 | tail -40 >&2 || true
    exit 1
  fi
  sleep 1
done

cat >"$ENV_FILE" <<EOF
# Generated by scripts/start_redis_bench.sh — source before RESP L2 bench runs.
REDIS_BENCH_HOST=127.0.0.1
REDIS_BENCH_PORT=${HOST_PORT}
EOF

echo "Wrote ${ENV_FILE} (REDIS_BENCH_HOST=127.0.0.1 REDIS_BENCH_PORT=${HOST_PORT})"
